function PageWorkspace({ page, onInvestigate }) {
  const [liveRows, setLiveRows] = useState([]);
  const [loading, setLoading] = useState(false);
  const [settings, setSettings] = useState({
    alert_threshold: 75,
    auto_route_escalations: true,
    daily_review_limit: 50,
    analyst_email: "analyst@fraudguard.ai",
    notifications_enabled: true,
    max_velocity_10m: 3,
    block_new_beneficiaries: false,
    risk_propagation_enabled: true,
    auto_create_cases: true,
    retention_days: 365,
  });
  const [settingsMessage, setSettingsMessage] = useState("");
  const [copilotInput, setCopilotInput] = useState("");
  const [copilotReply, setCopilotReply] = useState(
    "I can explain transaction risk, evidence, and recommended actions. Ask about a customer, merchant, case, or alert."
  );
  const [alertSummary, setAlertSummary] = useState(null);
  const [scenarioMessage, setScenarioMessage] = useState("");
  const [selectedRecord, setSelectedRecord] = useState(null);

  useEffect(() => {
    const endpointMap = {
      Alerts: "/api/alerts",
      Cases: "/api/cases",
      Transactions: "/api/transactions",
      Investigations: "/api/cases",
      "Network Analysis": "/api/fraud-rings",
      "Audit Logs": "/api/audit",
      Customers: "/api/customers",
      Merchants: "/api/merchants",
      Reports: "/api/reports",
    };

    const endpoint = endpointMap[page];

    if (!endpoint) {
      setLiveRows([]);
      return;
    }

    setLoading(true);
    fetch(endpoint)
      .then((response) => response.json())
      .then((data) => setLiveRows(Array.isArray(data) ? data : []))
      .catch(() => setLiveRows([]))
      .finally(() => setLoading(false));
  }, [page]);

  useEffect(() => {
    if (page !== "Alerts") return;
    fetch("/api/alerts/summary")
      .then((response) => response.json())
      .then(setAlertSummary)
      .catch(() => setAlertSummary(null));
  }, [page]);

  useEffect(() => {
    if (page !== "Settings") return;

    fetch("/api/settings")
      .then((response) => response.json())
      .then((data) => setSettings({ ...settings, ...data }))
      .catch(() => setSettings({
        alert_threshold: 75,
        auto_route_escalations: true,
        daily_review_limit: 50,
        analyst_email: "analyst@fraudguard.ai",
        notifications_enabled: true,
        max_velocity_10m: 3,
        block_new_beneficiaries: false,
        risk_propagation_enabled: true,
        auto_create_cases: true,
        retention_days: 365,
      }));
  }, [page]);

  const saveSettings = async () => {
    try {
      const response = await fetch("/api/settings", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(settings),
      });

      if (!response.ok) throw new Error("Failed");

      const data = await response.json();
      setSettings(data);
      setSettingsMessage("Settings saved successfully.");
    } catch {
      setSettingsMessage("Unable to save settings right now.");
    }
  };

  const askCopilot = async () => {
    const message = copilotInput.trim();
    if (!message) return;

    setCopilotReply("Analyzing live signals...");

    try {
      const response = await fetch("/api/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ message }),
      });
      const data = await response.json();
      setCopilotReply(data.answer || "I couldn't produce a valid answer.");
    } catch {
      setCopilotReply("The copilot service is temporarily unavailable. Please retry in a moment.");
    }

    setCopilotInput("");
  };

  const runScenario = async (scenario) => {
    setScenarioMessage("Creating live demo scenario...");
    try {
      const response = await fetch(`/api/demo-scenarios/${scenario}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ customer_id: "C101" }),
      });
      const data = await response.json();
      if (!response.ok) throw new Error(data.detail || "Scenario failed");
      setScenarioMessage(`${scenario} created: ${data.transaction_id} / risk ${data.risk_score}`);
    } catch (error) {
      setScenarioMessage(error.message);
    }
  };

  if (page === "Transactions") {
    return <TransactionsPage onInvestigate={onInvestigate} />;
  }

  if (page === "AI Copilot") {
    return (
      <div className="workspace-page">
        <div className="workspace-header">
          <div>
            <div className="workspace-title">
              <Bot size={28} />
              <span>AI Investigation Copilot</span>
            </div>
            <div className="workspace-subtitle">Ask the system about risk, evidence, and recommended actions.</div>
          </div>
          <div className="workspace-status"><span className="status-dot"></span>AI Ready</div>
        </div>

        <div className="workspace-main-card">
          <div className="workspace-main-header">
            <div>
              <h2>Copilot</h2>
              <p>Live fraud intelligence assistant</p>
            </div>
          </div>

          <div className="workspace-main-header" style={{ marginTop: 12 }}>
            <div style={{ width: "100%", background: "#111827", border: "1px solid #263243", borderRadius: 12, padding: 16, color: "#e5e7eb" }}>
              {copilotReply}
            </div>
          </div>

          <div style={{ display: "flex", gap: 12, marginTop: 18 }}>
            <input
              value={copilotInput}
              onChange={(e) => setCopilotInput(e.target.value)}
              onKeyDown={(e) => e.key === "Enter" && askCopilot()}
              placeholder="Ask: Why is the highest risk transaction suspicious?"
              style={{ flex: 1, background: "#0f172a", color: "#f8fafc", border: "1px solid #364152", borderRadius: 10, padding: "12px 14px" }}
            />
            <button className="workspace-action" onClick={askCopilot}>Ask Copilot</button>
          </div>

          <div style={{ marginTop: 24 }}>
            <h3>Demo scenarios</h3>
            <div style={{ display: "flex", flexWrap: "wrap", gap: 8 }}>
              {["account-takeover", "mule-account", "fraud-ring", "structuring", "suspicious-beneficiary"].map((scenario) => (
                <button className="workspace-action" key={scenario} onClick={() => runScenario(scenario)}>{scenario.replaceAll("-", " ")}</button>
              ))}
            </div>
            {scenarioMessage && <small>{scenarioMessage}</small>}
          </div>
        </div>
      </div>
    );
  }

  if (page === "Settings") {
    return (
      <div className="workspace-page">
        <div className="workspace-header">
          <div>
            <div className="workspace-title">
              <Settings size={28} />
              <span>System Settings</span>
            </div>
            <div className="workspace-subtitle">Tune thresholds, routing, and analyst preferences.</div>
          </div>
          <div className="workspace-status"><span className="status-dot"></span>Operational</div>
        </div>

        <div className="workspace-main-card">
          <div className="workspace-main-header">
            <div>
              <h2>FraudGuard Controls</h2>
              <p>Configure alerting and analyst workflow</p>
            </div>
          </div>

          <div style={{ display: "grid", gap: 16, marginTop: 18 }}>
            <label style={{ display: "grid", gap: 8 }}>
              <span>Alert threshold</span>
              <input
                type="number"
                min="0"
                max="100"
                value={settings.alert_threshold}
                onChange={(e) => setSettings({ ...settings, alert_threshold: Number(e.target.value) })}
                style={{ background: "#0f172a", color: "#f8fafc", border: "1px solid #364152", borderRadius: 10, padding: 10 }}
              />
            </label>

            <label style={{ display: "grid", gap: 8 }}>
              <span>Daily review limit</span>
              <input
                type="number"
                min="1"
                value={settings.daily_review_limit}
                onChange={(e) => setSettings({ ...settings, daily_review_limit: Number(e.target.value) })}
                style={{ background: "#0f172a", color: "#f8fafc", border: "1px solid #364152", borderRadius: 10, padding: 10 }}
              />
            </label>

            <label style={{ display: "grid", gap: 8 }}>
              <span>Analyst email</span>
              <input
                type="email"
                value={settings.analyst_email}
                onChange={(e) => setSettings({ ...settings, analyst_email: e.target.value })}
                style={{ background: "#0f172a", color: "#f8fafc", border: "1px solid #364152", borderRadius: 10, padding: 10 }}
              />
            </label>

            <label style={{ display: "grid", gap: 8 }}>
              <span>Velocity limit per 10 minutes</span>
              <input type="number" min="1" max="50" value={settings.max_velocity_10m} onChange={(e) => setSettings({ ...settings, max_velocity_10m: Number(e.target.value) })} style={{ background: "#0f172a", color: "#f8fafc", border: "1px solid #364152", borderRadius: 10, padding: 10 }} />
            </label>

            <label style={{ display: "grid", gap: 8 }}>
              <span>Evidence retention days</span>
              <input type="number" min="30" max="3650" value={settings.retention_days} onChange={(e) => setSettings({ ...settings, retention_days: Number(e.target.value) })} style={{ background: "#0f172a", color: "#f8fafc", border: "1px solid #364152", borderRadius: 10, padding: 10 }} />
            </label>

            <label style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 12 }}>
              <span>Route escalations automatically</span>
              <input type="checkbox" checked={settings.auto_route_escalations} onChange={(e) => setSettings({ ...settings, auto_route_escalations: e.target.checked })} />
            </label>

            <label style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 12 }}>
              <span>Notifications enabled</span>
              <input type="checkbox" checked={settings.notifications_enabled} onChange={(e) => setSettings({ ...settings, notifications_enabled: e.target.checked })} />
            </label>

            <label style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 12 }}>
              <span>Block new beneficiaries automatically</span>
              <input type="checkbox" checked={settings.block_new_beneficiaries} onChange={(e) => setSettings({ ...settings, block_new_beneficiaries: e.target.checked })} />
            </label>

            <label style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 12 }}>
              <span>Enable network risk propagation</span>
              <input type="checkbox" checked={settings.risk_propagation_enabled} onChange={(e) => setSettings({ ...settings, risk_propagation_enabled: e.target.checked })} />
            </label>

            <label style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 12 }}>
              <span>Auto-create investigation cases</span>
              <input type="checkbox" checked={settings.auto_create_cases} onChange={(e) => setSettings({ ...settings, auto_create_cases: e.target.checked })} />
            </label>

            <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", gap: 12, marginTop: 8 }}>
              <button className="workspace-action" onClick={saveSettings}>Save settings</button>
              {settingsMessage && <small style={{ color: "#a7f3d0" }}>{settingsMessage}</small>}
            </div>
          </div>
        </div>
      </div>
    );
  }

  const config =
    pageConfig[page] || pageConfig.Transactions;

  const PageIcon = config.icon;

  const renderLiveRows = () => {
    if (loading) {
      return <div className="workspace-empty">Loading live data...</div>;
    }

    if (!liveRows.length) {
      return <div className="workspace-empty">No live records available yet.</div>;
    }

    if (page === "Alerts") {
      return liveRows.map((alert) => (
        <div className="workspace-list-item" key={alert.transaction_id || alert.id}>
          <div>
            <strong>{alert.type || "Risk alert"}</strong>
            <div className="workspace-list-meta">{alert.location || alert.customer_id}</div>
          </div>
          <div className="workspace-list-badge">{alert.risk_score ?? alert.amount ?? "Live"}</div>
        </div>
      ));
    }

    if (page === "Network Analysis") {
      return liveRows.map((ring) => (
        <div className="workspace-list-item" key={ring.ring_id}>
          <div>
            <strong>{ring.ring_id} / {ring.device_id}</strong>
            <div className="workspace-list-meta">{ring.customer_count} customers, {ring.transaction_count} transactions</div>
          </div>
          <div className="workspace-list-badge">{ring.high_risk_count} high risk</div>
        </div>
      ));
    }

    if (page === "Customers") {
      return liveRows.map((customer) => (
        <div className="workspace-list-item" key={customer.id}>
          <div><strong>{customer.name}</strong><div className="workspace-list-meta">{customer.id} / {customer.transaction_count} transactions</div></div>
          <div className="workspace-list-badge">Risk {Number(customer.risk_score).toFixed(1)}</div>
        </div>
      ));
    }

    if (page === "Merchants") {
      return liveRows.map((merchant) => (
        <div className="workspace-list-item" key={merchant.merchant}>
          <div><strong>{merchant.merchant}</strong><div className="workspace-list-meta">{merchant.transaction_count} transactions / {merchant.high_risk_count} high risk</div></div>
          <div className="workspace-list-badge">Risk {Number(merchant.risk_score).toFixed(1)}</div>
        </div>
      ));
    }

    if (page === "Reports") {
      return liveRows.map((report) => (
        <div className="workspace-list-item" key={report.report_id}>
          <div><strong>{report.report_id}</strong><div className="workspace-list-meta">{report.transaction_id} / {report.status}</div></div>
          <a className="workspace-list-badge" href={`/api/reports/${report.transaction_id}.pdf`}>PDF</a>
        </div>
      ));
    }

    return liveRows.slice(0, 5).map((item) => (
      <div className="workspace-list-item" key={item.id || item.transaction_id}>
        <div>
          <strong>{item.id || item.transaction_id || "Record"}</strong>
          <div className="workspace-list-meta">{item.status || item.customer_id || item.type || "Available"}</div>
        </div>
        <div className="workspace-list-badge">{item.risk_score ?? item.amount ?? "Ready"}</div>
      </div>
    ));
  };


  return (

    <div className="workspace-page">


      {/* HEADER */}

      <div className="workspace-header">

        <div>

          <div className="workspace-title">

            <PageIcon size={28} />

            <span>
              {config.title}
            </span>

          </div>

          <div className="workspace-subtitle">
            {config.subtitle}
          </div>

        </div>


        <div className="workspace-status">

          <span className="status-dot"></span>

          System Operational

        </div>

      </div>


      {/* STAT CARDS */}

      <div className="workspace-grid">

        {config.stats.map(([label, value]) => (

          <div
            className="workspace-card"
            key={label}
          >

            <div className="workspace-card-top">

              <span className="workspace-card-label">
                {label}
              </span>

              <BarChart3 size={17} />

            </div>

            <div className="workspace-stat">
              {value}
            </div>

            <div className="workspace-card-footer">

              <Activity size={14} />

              Live intelligence

            </div>

          </div>

        ))}

      </div>


      {/* MAIN WORKSPACE */}

      <div className="workspace-main-card">

        {page === "Alerts" && alertSummary && (
          <div className="workspace-grid" style={{ marginBottom: 18 }}>
            {Object.entries(alertSummary).map(([priority, count]) => (
              <div className="workspace-card" key={priority}>
                <div className="workspace-card-label">{priority}</div>
                <div className="workspace-stat">{count}</div>
                <div className="workspace-card-footer">Priority queue</div>
              </div>
            ))}
          </div>
        )}


        <div className="workspace-main-header">

          <div>

            <h2>
              {config.title}
            </h2>

            <p>
              Advanced fraud intelligence workspace
            </p>

          </div>


          <button className="workspace-action">

            <Search size={16} />

            Search

          </button>

        </div>


        {/* SEARCH */}

        <div className="workspace-search">

          <Search size={18} />

          <input
            type="text"
            placeholder={`Search ${page.toLowerCase()}...`}
          />

        </div>


        {/* TABLE */}

        <div className="workspace-table-wrapper">

          <table className="workspace-table">

            <thead>

              <tr>

                <th>ID</th>

                <th>Entity</th>

                <th>Risk</th>

                <th>Status</th>

                <th>Last Activity</th>

                <th>Action</th>

              </tr>

            </thead>


            <tbody>{liveRows.slice(0, 10).map((item) => (
              <tr key={item.id || item.transaction_id || item.report_id || item.ring_id}>
                <td>{item.id || item.transaction_id || item.report_id || item.ring_id}</td>
                <td>{item.customer_name || item.customer_id || item.merchant || item.device_id || "Live intelligence"}</td>
                <td><span className="risk-high">{Math.round(item.risk_score || item.high_risk_count || 0)}</span></td>
                <td><span className="status-badge status-review">{item.status || "Active"}</span></td>
                <td>{item.timestamp || item.generated_at || "Live"}</td>
                <td><button className="table-action-button" onClick={() => setSelectedRecord(item)}>View</button></td>
              </tr>
            ))}</tbody>

          </table>

        </div>

        {selectedRecord && (
          <div className="workspace-main-card" style={{ marginTop: 16 }}>
            <div className="workspace-main-header">
              <div>
                <h2>Record details</h2>
                <p>{selectedRecord.id || selectedRecord.transaction_id || selectedRecord.report_id || selectedRecord.ring_id}</p>
              </div>
              <button className="workspace-action" onClick={() => setSelectedRecord(null)}>Close</button>
            </div>
            <pre style={{ whiteSpace: "pre-wrap", color: "#cbd5e1", margin: 0 }}>{JSON.stringify(selectedRecord, null, 2)}</pre>
            {(selectedRecord.transaction_id || selectedRecord.id?.startsWith("TXN")) && (
              <a className="workspace-action" href={`/api/reports/${selectedRecord.transaction_id || selectedRecord.id}.pdf`} style={{ display: "inline-block", marginTop: 14 }}>Download report</a>
            )}
          </div>
        )}

      </div>


      {/* AI AGENTS */}

      <div className="workspace-agent-panel">

        <div className="agent-panel-header">

          <div>

            <h2>

              <Bot size={20} />

              Multi-Agent Intelligence

            </h2>

            <p>
              FraudGuard AI agents are analyzing incoming intelligence.
            </p>

          </div>

          <span className="agent-live">
            ● LIVE
          </span>

        </div>


        <div className="agent-list">

          <div className="agent-item">

            <div className="agent-name">

              <Activity size={16} />

              Transaction Pattern Agent

            </div>

            <span className="agent-online">
              ONLINE
            </span>

          </div>


          <div className="agent-item">

            <div className="agent-name">

              <Users size={16} />

              Customer History Agent

            </div>

            <span className="agent-online">
              ONLINE
            </span>

          </div>


          <div className="agent-item">

            <div className="agent-name">

              <AlertTriangle size={16} />

              Risk Scoring Agent

            </div>

            <span className="agent-online">
              ONLINE
            </span>

          </div>


          <div className="agent-item">

            <div className="agent-name">

              <Network size={16} />

              Network Intelligence Agent

            </div>

            <span className="agent-online">
              ONLINE
            </span>

          </div>

        </div>

      </div>


    </div>

  );
}


export default PageWorkspace;